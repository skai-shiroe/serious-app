/**
 * Recherche d'emojis : matche les CATÉGORIES (les emojis n'ont pas de nom).
 * « coeur » ouvre la catégorie Coeurs, « nature » la catégorie Nature…
 */
export function searchEmojis(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return EMOJI_CATEGORIES.filter(
    (c) => c.label.toLowerCase().includes(q) || c.id.includes(q)
  ).flatMap((c) => c.emojis);
}
